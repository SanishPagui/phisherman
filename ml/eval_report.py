"""
eval_report.py — assemble assets/results.json read by the in-app Metrics screen and
used to fill the pitch slides (PS4 Section 11.3).

Pulls results_link.json + results_sms.json produced by the training scripts, adds a
voice summary (filled from your recorded scripts) and latency placeholders (filled
from the phone, measured with System.nanoTime per Section 11.2). Every number carries
an N and a dataset label so nobody in the room reads it differently.
"""

import argparse
import datetime
import json
import os

HERE = os.path.dirname(__file__)


def load(path, default):
    try:
        with open(path, encoding="utf-8") as fh:
            return json.load(fh)
    except FileNotFoundError:
        return default


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--assets", default=os.path.join(HERE, "..", "android", "app", "src", "main", "assets"))
    args = ap.parse_args()

    link = load(os.path.join(HERE, "results_link.json"), {})
    sms = load(os.path.join(HERE, "results_sms.json"), {})

    results = {
        "generated": datetime.date.today().isoformat(),
        "dataNote": "SYNTHETIC datasets (generated by gen_data.py) — replace with real "
                    "licensed data (URL-Phish, Kaggle/Mendeley smishing) before quoting as results. "
                    "'Fraud detection rate' = recall on the phishing class.",
        "link": {
            "dataset": "synthetic train_source (domain-split hold-out)",
            "threshold": link.get("threshold_dangerous"),
            "test": link.get("test", {}),
            "unseen": link.get("unseen", {}),
        },
        "sms": {
            "dataset": "synthetic sms_train (20% hold-out)",
            "nSynthetic": sms.get("n_synthetic", 0),
            "test": {k: sms[k] for k in ("precision", "recall", "fpr", "f1", "n", "tp", "fp", "fn", "tn") if k in sms},
        },
        "voice": {
            "dataset": "recorded scripts (fill after Phase 4 runs)",
            "scamScripts": {"n": 0, "detected": 0},
            "normalConversations": {"n": 0, "falseAlarms": 0},
            "avgTimeToRedSeconds": None,
            "note": "Tiny sample by design — say so on the slide."
        },
        "latencyMs": {
            "linkP50": None, "linkP95": None, "smsP50": None, "smsP95": None,
            "note": "Measured in-app with System.nanoTime on the demo phone; fill before the pitch."
        },
    }

    out = os.path.join(args.assets, "results.json")
    with open(out, "w", encoding="utf-8") as fh:
        json.dump(results, fh, indent=2)
    print(f"Wrote {out}")
    print(json.dumps(results["link"], indent=2))
    print(json.dumps(results["sms"], indent=2))


if __name__ == "__main__":
    main()
